import assert from 'node:assert/strict'
import { readFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { chromium } from 'playwright'
import { verifyCanvas } from './verify-browser.mjs'

// This runner accepts only an explicitly generated fixture descriptor. Service
// credentials stay inside this process and never enter logs or saved artifacts.
const descriptor = process.argv[2]
if (!descriptor) throw new Error('Usage: node web/verify-fixture.mjs <isolated-browser-fixture.json>')
const fixture = JSON.parse(await readFile(descriptor, 'utf8'))
assert.ok(path.basename(fixture.directory).startsWith('harnessl3-browser-'), 'requires an isolated browser fixture')
const service = JSON.parse(await readFile(path.join(fixture.dataRoot, 'service.json'), 'utf8'))
const nonce = await fetch(service.url + '/browser-session', { method: 'POST', headers: { authorization: 'Bearer ' + service.token } }).then(response => { assert.equal(response.status, 200); return response.json() })
const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL ?? (process.platform === 'win32' ? 'msedge' : undefined) })
const results = [], pageErrors = []
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.on('pageerror', error => pageErrors.push(error.message))
  const original = service.url + '/#' + new URLSearchParams({ code: nonce.code, worktree: fixture.target.worktreeId, task: fixture.entry.taskId })
  results.push(await verifyCanvas(page, original))
  assert.equal(new URL(page.url()).hash, '', 'one-use code is removed')
  await mkdir('web/validation', { recursive: true })
  await page.screenshot({ path: 'web/validation/formal-overview.png', fullPage: true })
  const targetView = await page.evaluate(async worktree => await fetch('/view?' + new URLSearchParams(worktree)).then(response => response.json()), { worktree: fixture.target.worktreeId, task: fixture.entry.taskId })
  const root = targetView.model.entities.find(entity => entity.entityType === 'object' && entity.parentId === null)
  await page.locator('[data-category-root="objects"] .map-main').click()
  const object = page.locator(`[data-node-id="object:${root.id}"]`)
  const anchorBefore = await object.boundingBox()
  await object.locator('.map-main').click()
  await page.waitForTimeout(350)
  const anchorAfter = await object.boundingBox()
  assert.ok(Math.abs(anchorAfter.x - anchorBefore.x) < 1 && Math.abs(anchorAfter.y - anchorBefore.y) < 1, 'expanded node keeps its screen anchor')
  const descendants = await page.locator('[data-map-depth="2"]').count()
  assert.ok(descendants)
  await page.locator('[data-category-root="objects"] .map-main').click()
  assert.equal(await page.locator('[data-map-depth="1"],[data-map-depth="2"]').count(), 0)
  await page.locator('[data-category-root="objects"] .map-main').click()
  assert.equal(await page.locator('[data-map-depth="2"]').count(), descendants, 'collapsed descendants keep local expansion state')
  await page.getByRole('button', { name: '收起全部层级', exact: true }).click()
  results.push({ canvasAnchor: 'fixed-on-expansion', collapsedDescendants: 'hidden-and-restored' })
  const beforeRead = targetView.task.lastReadAt
  const selected = targetView.task.skillPlan.skills[0]
  await page.locator('[data-skill-selector]').click()
  assert.equal(await page.locator('[data-skill-folder]').count(), new Set(targetView.task.skillPlan.skills.map(skill => skill.group)).size)
  await page.getByRole('button', { name: '概览全部内容', exact: true }).click()
  await page.locator(`[data-skill-folder="${selected.group}"] .skill-lane-main`).click()
  await page.getByRole('button', { name: '概览全部内容', exact: true }).click()
  assert.equal(await page.locator('[data-skill-file]').count(), 0, 'methods remain closed until clicked')
  await page.locator(`[data-skill-id="${selected.id}"] .skill-lane-main`).click()
  await page.getByRole('button', { name: '概览全部内容', exact: true }).click()
  const file = selected.files.find(file => file.path === 'SKILL.md')
  await page.locator(`[data-skill-file-owner="${selected.id}"][data-skill-file="${file.path}"]`).click()
  await page.getByRole('button', { name: '网页预览归档文件SKILL.md', exact: true }).click()
  const nativeText = page.getByRole('textbox', { name: '技能归档文件原文', exact: true })
  await nativeText.waitFor()
  assert.ok((await nativeText.inputValue()).length)
  await page.getByRole('button', { name: '关闭详情', exact: true }).click()
  const afterRead = await page.evaluate(async args => await fetch('/view?' + new URLSearchParams(args)).then(response => response.json()), { worktree: fixture.target.worktreeId, task: fixture.entry.taskId })
  assert.equal(afterRead.task.lastReadAt, beforeRead, 'web skill-file preview does not renew context retention')
  assert.equal(afterRead.task.batches.length, targetView.task.batches.length, 'skill-file receipt does not create a context batch')
  results.push({ nativeSkills: 'folder→skill→file→explicit-archived-preview', contextReadUnchanged: true })

  await page.goto(service.url + '/?' + new URLSearchParams({ worktree: fixture.target.worktreeId, task: fixture.legacy.id, history: '1' }))
  await page.waitForFunction(() => document.querySelector('[data-format="prototype-v0.16"]') && !document.querySelector('.view-loading'))
  assert.equal(await page.getByTestId('app-shell').getAttribute('data-task-id'), fixture.legacy.id)
  assert.equal(await page.getByTestId('app-shell').getAttribute('data-historical'), 'true')
  assert.equal(await page.locator('[data-output-count]').getAttribute('data-output-count'), '1')
  await page.locator('[data-category-root="objects"] .map-main').click()
  assert.equal(await page.locator('[data-node-id="object:example"]').count(), 1)
  await page.locator('[data-node-id="object:example"] .map-main').click()
  assert.equal(await page.locator('[data-node-id="object:example.worker"]').getAttribute('data-node-state'), 'returned')
  await page.locator('[data-skill-selector]').click()
  assert.equal(await page.locator('[data-skill-folder="engineering"]').count(), 1)
  await page.locator('[data-skill-folder="engineering"] .skill-lane-main').click()
  assert.equal(await page.locator('[data-skill-id="engineering/original-method"]').count(), 1)
  await page.locator('[data-skill-id] .skill-lane-main').click()
  await page.getByRole('button', { name: '查看技能文件SKILL.md', exact: true }).click()
  await page.getByTestId('legacy-skills').waitFor()
  await page.getByRole('button', { name: '预览归档', exact: true }).click()
  const archivedText = page.getByRole('textbox', { name: '旧技能归档原文', exact: true })
  await archivedText.waitFor()
  assert.match(await archivedText.inputValue(), /SYNTHETIC LEGACY METHOD/)
  await page.getByRole('button', { name: '关闭详情', exact: true }).click()
  await page.getByRole('button', { name: '项目结构', exact: true }).click()
  assert.equal(await page.locator('[data-c4-view="original-view"]').count(), 1)
  assert.equal(await page.locator('[data-c4-node="example.worker"]').count(), 1)
  await page.screenshot({ path: 'web/validation/legacy-c4.png', fullPage: true })
  results.push({ legacy: ['original-dot-hierarchy', 'original-group', 'original-file-bytes', 'original-c4'] })

  await page.goto(service.url + '/?' + new URLSearchParams({ worktree: fixture.target.worktreeId, task: fixture.entry.taskId, batch: fixture.firstBatch, history: '1' }))
  await page.getByTestId('history-fixed').waitFor()
  await page.waitForFunction(() => !document.querySelector('.view-loading') && document.querySelector('[data-output-count]')?.getAttribute('data-output-count') !== '0')
  const frozenSeq = await page.getByTestId('app-shell').getAttribute('data-view-seq')
  const frozenOutput = await page.locator('[data-output-count]').getAttribute('data-output-count')
  assert.equal(await page.getByRole('combobox', { name: '恢复到指定批次' }).inputValue(), fixture.firstBatch)
  await page.waitForFunction(() => document.querySelector('[data-testid="connection-status"]')?.getAttribute('data-state') === 'connected')
  await page.evaluate(async args => {
    const requestId = crypto.randomUUID()
    const result = await fetch('/rpc', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Harness-Web': '1' }, body: JSON.stringify({ operation: 'task read', positionals: [args.task], flags: { worktree: args.worktree, file: '-' }, requestId, input: { schemaVersion: 1, requestId, files: [{ skillId: args.skill.id, path: args.file.path, expectedHash: args.file.hash }] } }) }).then(response => response.json())
    if (!result.ok) throw new Error(result.error.code + ': ' + result.error.message)
  }, { task: fixture.entry.taskId, worktree: fixture.target.worktreeId, skill: selected, file })
  await page.getByTestId('history-update').waitFor()
  assert.equal(await page.getByTestId('app-shell').getAttribute('data-view-seq'), frozenSeq)
  assert.equal(await page.locator('[data-output-count]').getAttribute('data-output-count'), frozenOutput)
  results.push({ historyBatch: 'fixed-across-real-commit', retentionBasis: 'unchanged' })

  await page.getByRole('combobox', { name: '选择工作区', exact: true }).selectOption(fixture.linked.worktreeId)
  await page.waitForFunction(id => document.querySelector('[data-testid="app-shell"]')?.getAttribute('data-route-worktree') === id && !document.querySelector('.view-loading'), fixture.linked.worktreeId)
  let delayed = false
  const delayedView = async route => {
    const url = new URL(route.request().url())
    if (!delayed && url.searchParams.get('worktree') === fixture.target.worktreeId && !url.searchParams.has('task')) {
      delayed = true
      try { const response = await route.fetch(); await new Promise(resolve => setTimeout(resolve, 350)); await route.fulfill({ response }) } catch { /* aborted by an explicit target switch */ }
    } else await route.continue()
  }
  await page.route('**/view?**', delayedView)
  await page.getByRole('combobox', { name: '选择工作区', exact: true }).selectOption(fixture.target.worktreeId)
  while (!delayed) await new Promise(resolve => setTimeout(resolve, 10))
  await page.getByRole('combobox', { name: '选择工作区', exact: true }).selectOption(fixture.linked.worktreeId)
  await page.waitForFunction(id => document.querySelector('[data-testid="app-shell"]')?.getAttribute('data-route-worktree') === id && !document.querySelector('.view-loading'), fixture.linked.worktreeId)
  await page.waitForTimeout(400)
  assert.equal(await page.getByTestId('app-shell').getAttribute('data-route-worktree'), fixture.linked.worktreeId)
  assert.equal(await page.getByTestId('app-shell').getAttribute('data-task-id'), '')
  assert.equal(await page.locator(`.task-select option[value="${fixture.entry.taskId}"]`).count(), 0, 'old worktree tasks never remain selectable in the new worktree')
  await page.unroute('**/view?**', delayedView)
  await page.getByRole('combobox', { name: '选择项目', exact: true }).selectOption(fixture.other.projectId)
  await page.waitForFunction(id => document.querySelector('[data-testid="app-shell"]')?.getAttribute('data-route-worktree') === id && !document.querySelector('.view-loading'), fixture.other.worktreeId)
  assert.equal(await page.getByRole('combobox', { name: '选择工作区', exact: true }).inputValue(), fixture.other.worktreeId)
  results.push({ targetIsolation: ['late-old-response-ignored', 'old-task-options-cleared', 'project-worktree-switch'] })

  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1, reducedMotion: 'reduce' })
  await phone.addCookies(await page.context().cookies())
  const mobile = await phone.newPage()
  mobile.on('pageerror', error => pageErrors.push(error.message))
  const requests = []
  mobile.on('request', request => requests.push(request.url()))
  await mobile.goto(service.url + '/?' + new URLSearchParams({ worktree: fixture.target.worktreeId, task: fixture.entry.taskId }))
  await mobile.waitForFunction(() => document.querySelector('[data-testid="app-shell"]')?.getAttribute('data-task-id') && !document.querySelector('.view-loading'))
  assert.equal(await mobile.locator('[data-map-depth="1"]').count(), 0)
  await mobile.screenshot({ path: 'web/validation/mobile-overview.png', fullPage: true })
  const world = mobile.locator('.world'), xBefore = await world.getAttribute('data-camera-x')
  const touch = await phone.newCDPSession(mobile)
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 25, y: 600 }] })
  await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 115, y: 630 }] })
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  assert.notEqual(await world.getAttribute('data-camera-x'), xBefore, 'one-finger pan')
  const scaleBefore = Number(await world.getAttribute('data-camera-scale'))
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 130, y: 440 }, { x: 250, y: 440 }] })
  await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 80, y: 440 }, { x: 300, y: 440 }] })
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  assert.ok(Number(await world.getAttribute('data-camera-scale')) > scaleBefore, 'two-finger zoom')
  await mobile.getByRole('button', { name: '五类', exact: true }).tap()
  assert.equal(await world.evaluate(element => element.classList.contains('camera-smooth')), false, 'reduced motion suppresses smooth camera')
  await phone.setOffline(true)
  await mobile.waitForFunction(() => document.querySelector('[data-testid="connection-status"]')?.getAttribute('data-state') === 'offline')
  await mobile.locator('[data-category-root="objects"] .map-main').tap()
  assert.ok(await mobile.locator('[data-map-depth="1"]').count(), 'cached model expands while offline')
  assert.ok(requests.every(url => new URL(url).origin === service.url), 'local resources have no external font/API dependency')
  results.push({ phone: ['390x844', 'one-finger-pan', 'two-finger-zoom', 'reduced-motion', 'offline-disclosure', 'same-origin-resources'] })
  await phone.close()
  assert.deepEqual(pageErrors, [], 'no browser runtime exceptions')
  console.log(JSON.stringify({ results, pageErrors }))
} finally { await browser.close() }
