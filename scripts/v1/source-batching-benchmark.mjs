import { mkdtemp, mkdir, writeFile, readFile } from 'node:fs/promises'
import { execFile as exec } from 'node:child_process'
import { promisify, isDeepStrictEqual } from 'node:util'
import { randomUUID, createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { performance } from 'node:perf_hooks'
import path from 'node:path'
import os from 'node:os'
import { generateDataset, writeDataset, summarizeSamples } from './benchmark.mjs'

const execFile = promisify(exec)
const candidate = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const options = {}
for (let i = 2; i < process.argv.length; i += 2) {
  const key = process.argv[i], value = process.argv[i + 1]
  if (!['--baseline-root', '--output', '--samples', '--files'].includes(key) || !value || options[key]) throw new Error('Use --baseline-root, --output, --samples, --files with one value each')
  options[key] = value
}
const baseline = path.resolve(options['--baseline-root'] ?? candidate)
const count = Number(options['--samples'] ?? 3), files = Number(options['--files'] ?? 1786)
if (!Number.isSafeInteger(count) || count < 3 || count > 10 || !Number.isSafeInteger(files) || files < 100 || files > 10000) throw new Error('Expected 3..10 samples and 100..10000 source files')
const output = path.resolve(options['--output'] ?? path.join(candidate, '.harness-local/validation/source-batching/cli-comparison.json'))
const base = await mkdtemp(path.join(os.tmpdir(), 'harnessl3-source-benchmark-'))
const root = path.join(base, 'source project'), dataset = generateDataset({ objects: 40 })
await mkdir(root); await writeDataset(root, dataset)
for (let i = 0; i < files; i++) {
  const directory = path.join(root, 'payload', 'group-' + i % 12, 'set-' + Math.floor(i / 12) % 9)
  await mkdir(directory, { recursive: true })
  await writeFile(path.join(directory, 'file-' + i + '.txt'), 'Synthetic source ' + i + '\n')
}
const git = (...args) => execFile('git', ['-C', root, ...args], { windowsHide: true })
await git('init', '-b', 'main'); await git('config', 'user.name', 'Harness benchmark'); await git('config', 'user.email', 'fixture@example.invalid')
await git('config', 'core.autocrlf', 'false'); await git('add', '.'); await git('commit', '-m', 'Synthetic source batching fixture')
const fixtureState = async () => ({ head: (await git('rev-parse', 'HEAD')).stdout.trim(), status: (await git('status', '--porcelain=v1', '-z', '--untracked-files=all')).stdout })
const report = { schemaVersion: 1, fixture: base, synthetic: true, environment: { node: process.version, platform: process.platform, cpu: os.cpus()[0]?.model, memory: os.totalmem() }, dimensions: { payloadFiles: files, objects: 40, views: 5, history: 'only tasks generated by this run; no copied user history' }, methodology: 'One cold task start prepares the running service, followed by at least three warm starts per implementation, then select/read/handoff and restart comparison. Same immutable Git checkout, independent data roots; shared machine, no forced OS cache flush. Peak RSS and CPU are daemon lifetime measurements, not operation deltas.', implementations: [], equalPackets: null }
report.fixtureBefore = await fixtureState()
const checkpoint = async () => { await mkdir(path.dirname(output), { recursive: true }); await writeFile(output, JSON.stringify(report, null, 2) + '\n') }
const hash = value => createHash('sha256').update(value).digest('hex')
const metricsCode = `import fs from 'node:fs';import{isMainThread}from'node:worker_threads';if(isMainThread){const dir=process.env.HARNESS_BATCH_METRICS;function save(){try{const r=process.resourceUsage();fs.mkdirSync(dir,{recursive:true});fs.writeFileSync(dir+'/'+process.pid+'.json',JSON.stringify({peakRSSBytes:Math.max(process.memoryUsage().rss,r.maxRSS*1024),userCPUTime:r.userCPUTime,systemCPUTime:r.systemCPUTime}))}catch{}}const t=setInterval(save,500);t.unref();process.on('exit',save);}`
const preload = '--import=data:text/javascript;base64,' + Buffer.from(metricsCode).toString('base64')
const packets = []
for (const [label, packageRoot] of [['baseline', baseline], ['candidate', candidate]]) {
  const dataRoot = path.join(base, label + '-data'), metrics = path.join(base, label + '-metrics')
  const item = { label, packageRoot, build: JSON.parse(await readFile(path.join(packageRoot, 'build/build-info.json'), 'utf8')), cold: [], warm: [], steps: [] }
  report.implementations.push(item); await checkpoint()
  const cli = async args => {
    const started = performance.now()
    console.log(JSON.stringify({ label, operation: args.slice(0, 2).join(' '), starting: true }))
    let response
    try {
      response = await execFile(process.execPath, [path.join(packageRoot, 'bin/harnessl3.mjs'), ...args, '--data-dir', dataRoot, '--json'], { cwd: root, windowsHide: true, env: { ...process.env, HARNESS_SKILLS_ROOT: '', HARNESSL3_HOME: '', HARNESS_BATCH_METRICS: metrics, NODE_OPTIONS: preload }, timeout: 600000, maxBuffer: 32 * 1024 * 1024 })
    } catch (error) { throw Object.assign(new Error('Benchmark CLI failed: ' + args.slice(0, 2).join(' ') + ' ' + (error.stdout ?? error.message)), { cause: error }) }
    const body = JSON.parse(response.stdout)
    if (!body.ok) throw new Error(JSON.stringify(body.error))
    return { body, ms: performance.now() - started }
  }
  const json = async (args, request) => { const file = path.join(base, randomUUID() + '.json'); await writeFile(file, JSON.stringify(request)); return cli([...args, '--file', file]) }
  const daemonStats = async () => {
    const descriptor = JSON.parse(await readFile(path.join(dataRoot, 'service.json'), 'utf8'))
    return JSON.parse(await readFile(path.join(metrics, descriptor.pid + '.json'), 'utf8'))
  }
  try {
    await cli(['init']); await cli(['serve', 'stop'])
    const cold = await cli(['task', 'start', '--title', 'Synthetic source batching entry'])
    item.cold.push({ ok: true, ms: cold.ms, ...(await daemonStats()) }); console.log(JSON.stringify({ label, phase: 'cold-start', ms: cold.ms })); await checkpoint()
    let entry
    for (let i = 0; i < count; i++) {
      entry = await cli(['task', 'start', '--title', 'Synthetic source batching sample'])
      item.warm.push({ ok: true, iteration: i, ms: entry.ms, ...(await daemonStats()) })
      console.log(JSON.stringify({ label, phase: 'warm-start', sample: i, ms: entry.ms })); await checkpoint()
    }
    const { taskId, binding, catalog } = entry.body.data
    const skill = catalog[0]
    const selected = await json(['task', 'select', taskId], { schemaVersion: 1, binding, context: { expand: [], read: [dataset.nodes[0].id], known: {} }, skills: [{ id: skill.id, reason: 'Synthetic archived-byte and handoff comparison' }] })
    item.steps.push({ operation: 'select', ms: selected.ms })
    const plan = selected.body.data.skillPlan
    const read = await json(['task', 'read', taskId], { schemaVersion: 1, throughBatchId: plan.batchId, files: plan.skills.flatMap(method => method.files.map(file => ({ skillId: method.id, path: file.path, expectedHash: file.hash }))) })
    item.steps.push({ operation: 'read', ms: read.ms })
    const before = await cli(['task', 'handoff', taskId]); item.steps.push({ operation: 'handoff', ms: before.ms })
    const saved = before.body.data
    packets.push({ packet: saved.packet, skills: saved.skillPlan.skills, files: read.body.data.files })
    item.packetHash = hash(JSON.stringify(saved.packet)); item.skillHash = hash(JSON.stringify(saved.skillPlan.skills))
    item.daemonMetrics = await daemonStats()
    await cli(['serve', 'stop'])
    const after = await cli(['task', 'handoff', taskId]); item.steps.push({ operation: 'restart-handoff', ms: after.ms })
    item.restartPreserved = isDeepStrictEqual(after.body.data, saved)
    if (!item.restartPreserved) throw new Error('Handoff changed after restart')
    item.warmSummary = summarizeSamples(item.warm)
    item.ok = true; await checkpoint()
  } catch (error) { item.ok = false; item.error = error.message; await checkpoint(); throw error }
  finally {
    try { await cli(['serve', 'stop']) }
    catch (error) { item.stopError = error.message; await checkpoint(); throw error }
  }
}
report.equalPackets = isDeepStrictEqual(packets[0], packets[1])
report.fixtureAfter = await fixtureState()
report.fixtureUnchanged = isDeepStrictEqual(report.fixtureBefore, report.fixtureAfter)
report.finishedAt = new Date().toISOString(); await checkpoint()
if (!report.equalPackets) throw new Error('Implementations returned different context/skill bytes')
if (!report.fixtureUnchanged) throw new Error('The source fixture changed during comparison')
console.log(JSON.stringify({ output, equalPackets: report.equalPackets, implementations: report.implementations.map(item => ({ label: item.label, cold: item.cold, warm: item.warmSummary, steps: item.steps, daemonMetrics: item.daemonMetrics })) }))
